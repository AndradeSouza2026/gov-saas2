-- 1. DESATIVAR TRIGGERS RESTRITIVOS QUE BLOQUEAVAM OS PEDIDOS
DROP TRIGGER IF EXISTS trg_antes_inserir_solicitacao ON public.solicitacoes;
DROP TRIGGER IF EXISTS trigger_atualizar_solicitacoes ON public.solicitacoes;
DROP TRIGGER IF EXISTS trg_solicitacoes_updated ON public.solicitacoes;

-- 2. GARANTIR COLUNAS NA TABELA SOLICITACOES
CREATE TABLE IF NOT EXISTS public.solicitacoes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    protocolo BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2001),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.solicitacoes
  ADD COLUMN IF NOT EXISTS protocolo_publico TEXT DEFAULT upper(substr(replace(gen_random_uuid()::text,'-',''),1,10)),
  ADD COLUMN IF NOT EXISTS prefeitura_id UUID,
  ADD COLUMN IF NOT EXISTS secretaria_id UUID,
  ADD COLUMN IF NOT EXISTS servico_id TEXT,
  ADD COLUMN IF NOT EXISTS servico_nome TEXT,
  ADD COLUMN IF NOT EXISTS servico_icone TEXT DEFAULT '📌',
  ADD COLUMN IF NOT EXISTS setor_responsavel TEXT,
  ADD COLUMN IF NOT EXISTS setor_sigla TEXT,
  ADD COLUMN IF NOT EXISTS cidadao_id UUID,
  ADD COLUMN IF NOT EXISTS cidadao_nome TEXT,
  ADD COLUMN IF NOT EXISTS cidadao_cpf TEXT,
  ADD COLUMN IF NOT EXISTS cidadao_telefone TEXT,
  ADD COLUMN IF NOT EXISTS cartao_sus TEXT,
  ADD COLUMN IF NOT EXISTS endereco_gps TEXT,
  ADD COLUMN IF NOT EXISTS endereco_rua TEXT,
  ADD COLUMN IF NOT EXISTS endereco_numero TEXT,
  ADD COLUMN IF NOT EXISTS endereco_bairro TEXT,
  ADD COLUMN IF NOT EXISTS endereco_referencia TEXT,
  ADD COLUMN IF NOT EXISTS latitude NUMERIC,
  ADD COLUMN IF NOT EXISTS longitude NUMERIC,
  ADD COLUMN IF NOT EXISTS google_maps_url TEXT,
  ADD COLUMN IF NOT EXISTS waze_url TEXT,
  ADD COLUMN IF NOT EXISTS google_maps_rota TEXT,
  ADD COLUMN IF NOT EXISTS unidade_preferencia TEXT,
  ADD COLUMN IF NOT EXISTS turno_preferencia TEXT,
  ADD COLUMN IF NOT EXISTS tipo_atendimento TEXT DEFAULT 'PRESENCIAL',
  ADD COLUMN IF NOT EXISTS descricao TEXT,
  ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'PENDENTE',
  ADD COLUMN IF NOT EXISTS resposta_prefeitura TEXT,
  ADD COLUMN IF NOT EXISTS agendado_para TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS prazo_limite TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS respostas_personalizadas JSONB DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now());

-- Permitir que servico_id e cidadao_id aceitem nulo (compatibilidade universal)
ALTER TABLE public.solicitacoes ALTER COLUMN servico_id DROP NOT NULL;
ALTER TABLE public.solicitacoes ALTER COLUMN cidadao_id DROP NOT NULL;

-- 3. PERMISSÕES DE ACESSO PARA API PÚBLICA (ANON E AUTHENTICATED)
GRANT USAGE ON SCHEMA public TO anon, authenticated, postgres, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, postgres, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, postgres, service_role;
GRANT ALL ON ALL ROUTINES IN SCHEMA public TO anon, authenticated, postgres, service_role;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, postgres, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, postgres, service_role;

-- 4. POLÍTICAS DE ROW LEVEL SECURITY (RLS) 100% ABERTAS PARA O APLICATIVO E PAINEL
