-- 1. CRIAÇÃO DA TABELA DE SERVIÇOS PÚBLICOS (CATÁLOGO DINÂMICO)
CREATE TABLE IF NOT EXISTS public.servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    icone TEXT NOT NULL DEFAULT '🏛️',
    secretaria TEXT NOT NULL,
    fluxo TEXT NOT NULL CHECK (fluxo IN ('AGENDAMENTO', 'CHAMADO')) DEFAULT 'CHAMADO',
    pede_agenda BOOLEAN NOT NULL DEFAULT false,
    pede_endereco BOOLEAN NOT NULL DEFAULT false,
    pede_sus BOOLEAN NOT NULL DEFAULT false,
    pede_foto BOOLEAN NOT NULL DEFAULT false,
    perguntas_extras JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. CRIAÇÃO DA TABELA DE SOLICITAÇÕES / CHAMADOS / AGENDAMENTOS DOS CIDADÃOS
CREATE TABLE IF NOT EXISTS public.solicitacoes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    protocolo BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2001),
    servico_id BIGINT REFERENCES public.servicos(id) ON DELETE SET NULL,
    servico_nome TEXT NOT NULL,
    icone TEXT DEFAULT '📋',
    secretaria TEXT NOT NULL,
    fluxo TEXT NOT NULL CHECK (fluxo IN ('AGENDAMENTO', 'CHAMADO')),
    cidadao_nome TEXT NOT NULL,
    cpf TEXT,
    telefone TEXT NOT NULL,
    cartao_sus TEXT,
    unidade_atendimento TEXT,
    turno TEXT,
    endereco TEXT,
    foto_url TEXT,
    detalhe_extra TEXT,
    respostas_extras JSONB DEFAULT '{}'::jsonb,
    descricao TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE', 'EM_ANDAMENTO', 'AGENDADO', 'CONCLUIDO', 'CANCELADO')),
    data_agendada TEXT,
    resposta_prefeitura TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Gatilho para atualizar o campo updated_at automaticamente
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_solicitacoes_updated_at ON public.solicitacoes;
CREATE TRIGGER trigger_solicitacoes_updated_at
BEFORE UPDATE ON public.solicitacoes
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

