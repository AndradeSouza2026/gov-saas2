-- ==============================================================================
-- SCHEMA COMPLETO SUPABASE - CONECTAPREFEITURA SAAS GOVTECH
-- Compatível com o código pronto para a Vercel
-- Execute no SQL Editor do Supabase (supabase.com/dashboard)
-- ==============================================================================

-- 1. TABELA DE PREFEITURAS (MUNICÍPIOS)
CREATE TABLE IF NOT EXISTS public.prefeituras (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nome TEXT NOT NULL,
    cidade_uf TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABELA DE SECRETARIAS
CREATE TABLE IF NOT EXISTS public.secretarias (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    prefeitura_id UUID REFERENCES public.prefeituras(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABELA DE CATÁLOGO DE SERVIÇOS
CREATE TABLE IF NOT EXISTS public.catalogo_servicos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    prefeitura_id UUID REFERENCES public.prefeituras(id) ON DELETE CASCADE,
    secretaria_id UUID REFERENCES public.secretarias(id) ON DELETE SET NULL,
    nome TEXT NOT NULL,
    icone TEXT NOT NULL DEFAULT '📌',
    tipo_fluxo TEXT NOT NULL CHECK (tipo_fluxo IN ('AGENDAMENTO', 'ZELADORIA')),
    exige_unidade_saude BOOLEAN DEFAULT false,
    exige_endereco BOOLEAN DEFAULT false,
    exige_cartao_sus BOOLEAN DEFAULT false,
    campos_personalizados JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. TABELA DE SOLICITAÇÕES / PROTOCOLOS DOS CIDADÃOS
CREATE TABLE IF NOT EXISTS public.solicitacoes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    protocolo BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2001),
    prefeitura_id UUID REFERENCES public.prefeituras(id) ON DELETE CASCADE,
    servico_id UUID REFERENCES public.catalogo_servicos(id) ON DELETE SET NULL,
    cidadao_nome TEXT NOT NULL,
    cidadao_cpf TEXT NOT NULL,
    cidadao_telefone TEXT NOT NULL,
    cartao_sus TEXT,
    endereco_gps TEXT,
    unidade_preferencia TEXT,
    turno_preferencia TEXT,
    respostas_personalizadas JSONB DEFAULT '{}'::jsonb,
    descricao TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE', 'EM_ANDAMENTO', 'AGENDADO', 'CONCLUIDO', 'CANCELADO')),
    resposta_prefeitura TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Gatilho para atualizar updated_at automaticamente
CREATE OR REPLACE FUNCTION public.handle_solicitacoes_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_atualizar_solicitacoes ON public.solicitacoes;
CREATE TRIGGER trigger_atualizar_solicitacoes
BEFORE UPDATE ON public.solicitacoes
FOR EACH ROW EXECUTE FUNCTION public.handle_solicitacoes_updated_at();

-- ==============================================================================
-- PERMISSÕES ROW LEVEL SECURITY (RLS)
-- ==============================================================================
ALTER TABLE public.prefeituras ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.secretarias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.catalogo_servicos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.solicitacoes ENABLE ROW LEVEL SECURITY;

-- Políticas de acesso público para teste e produção inicial do SaaS
CREATE POLICY "Permitir tudo prefeituras" ON public.prefeituras FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Permitir tudo secretarias" ON public.secretarias FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Permitir tudo catalogo_servicos" ON public.catalogo_servicos FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Permitir tudo solicitacoes" ON public.solicitacoes FOR ALL USING (true) WITH CHECK (true);

-- ==============================================================================
-- HABILITAR REALTIME
-- ==============================================================================
ALTER PUBLICATION supabase_realtime ADD TABLE public.solicitacoes;
ALTER PUBLICATION supabase_realtime ADD TABLE public.catalogo_servicos;

